#wap for numpy array properties and functions
import numpy as np

a = np.array([10, 20, 30, 40, 50])

print("Array:", a)
print("Dimension:", a.ndim)
print("Shape:", a.shape)
print("Size:", a.size)
print("Data type:", a.dtype)

print("Sum:", np.sum(a))
print("Maximum:", np.max(a))
print("Minimum:", np.min(a))
print("Mean:", np.mean(a))
 
